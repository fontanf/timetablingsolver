// API of the web page, run by Cloudflare Pages Functions (see
// 'wasm/functions/api/[[path]].js') with a D1 database bound as 'DB'.
//
// The data is encrypted in the browsers with keys which are never sent to the
// server (see 'web/polls.js' and 'web/sync.js'): the server only stores
// opaque strings.
//
// Polls: a teacher creates a poll, the students send their responses, the
// teacher reads them.
//
//     POST   /api/polls                       {adminToken, definition} -> {pollId}
//                                              (first versions of the page)
//     GET    /api/polls/:poll                 -> {definition, closed}
//     PUT    /api/polls/:poll                 admin; {definition?, closed?}
//                                              (creates the poll if it doesn't exist:
//                                              the admin token is the one given)
//     DELETE /api/polls/:poll                 admin
//     GET    /api/polls/:poll/responses       admin -> {responses: [{id, data, updated}]}
//     GET    /api/polls/:poll/responses/:id   response token -> {data, updated}
//     PUT    /api/polls/:poll/responses/:id   response token; {data}
//     PUT    /api/polls/:poll/publications    admin; {publications: [{responseId, tokenHash?, data}]}
//     DELETE /api/polls/:poll/publications    admin
//     GET    /api/polls/:poll/responses/:id/publication
//                                              response token -> {data}
//
// The publications are the timetable of each participant, published by the
// organizer: the one of a response is given to the holder of its token (the
// one of the response, or 'tokenHash', the SHA-256 hash of the token of the
// personal link of the participant, for the participants who didn't answer
// with it). Publishing replaces the previous publications.
//
// The tokens are generated by the browsers and sent in the header
// 'Authorization: Bearer <token>' (the admin token of a poll, or the token of
// a response, given when the response is created); the server only stores
// their SHA-256 hashes. The id and the token of a response are generated by
// the browser of the student, or by the browser of the teacher for the
// personal link of a student. Errors: '{error: <code>}'.
//
// A poll expires two months after its last modification (by the organizer, or
// a response of a participant); the expired polls are removed when a poll is
// created.
//
// Projects: the projects of the teachers, to open them on several devices.
//
//     GET    /api/projects/:project   token -> {data, version}
//     PUT    /api/projects/:project   token; {data, version} -> {version}
//     DELETE /api/projects/:project   token
//
// The id and the token of a project are generated by the browser which
// creates it; the first PUT creates it (with 'version' 0). 'version' is the
// version the data is based on: if the project was modified since (by
// another device), the PUT fails with a 409 error '{error: "conflict",
// version, data}', with the current version. A project expires two months
// after its last modification; the expired projects are removed when a
// project is created. The browsers keep the projects: they send them again
// (with 'version' 0) if they expired.

export const LIMITS = {
    definitionLength: 100_000,
    responseLength: 50_000,
    responsesPerPoll: 500,
    publicationLength: 20_000,
    projectLength: 1_000_000,
};

// Two months after the last modification (of a poll or a project).
const EXPIRATION = 61 * 24 * 3600 * 1000;

// The ids and tokens: random, base64url, generated by 'randomToken'.
const TOKEN = /^[A-Za-z0-9_-]{22,64}$/;

const SCHEMA = [
    `CREATE TABLE IF NOT EXISTS polls (
        id TEXT PRIMARY KEY,
        admin_hash TEXT NOT NULL,
        definition TEXT NOT NULL,
        closed INTEGER NOT NULL DEFAULT 0,
        created INTEGER NOT NULL,
        updated INTEGER NOT NULL,
        expires INTEGER NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS responses (
        poll_id TEXT NOT NULL,
        id TEXT NOT NULL,
        token_hash TEXT NOT NULL,
        data TEXT NOT NULL,
        created INTEGER NOT NULL,
        updated INTEGER NOT NULL,
        PRIMARY KEY (poll_id, id))`,
    "CREATE INDEX IF NOT EXISTS polls_expires ON polls (expires)",
    `CREATE TABLE IF NOT EXISTS publications (
        poll_id TEXT NOT NULL,
        response_id TEXT NOT NULL,
        token_hash TEXT,
        data TEXT NOT NULL,
        PRIMARY KEY (poll_id, response_id))`,
    `CREATE TABLE IF NOT EXISTS projects (
        id TEXT PRIMARY KEY,
        token_hash TEXT NOT NULL,
        data TEXT NOT NULL,
        version INTEGER NOT NULL,
        created INTEGER NOT NULL,
        updated INTEGER NOT NULL,
        expires INTEGER NOT NULL)`,
    "CREATE INDEX IF NOT EXISTS projects_expires ON projects (expires)",
];

// The databases where the schema was created by this instance.
const initialized = new WeakSet();

async function initialize(db) {
    if (initialized.has(db))
        return;
    for (const statement of SCHEMA)
        await db.prepare(statement).run();
    initialized.add(db);
}

class ApiError extends Error {
    constructor(status, code) {
        super(code);
        this.status = status;
        this.code = code;
    }
}

function json(body, status = 200) {
    return new Response(JSON.stringify(body), {
        status,
        headers: {"Content-Type": "application/json", "Cache-Control": "no-store"},
    });
}

function randomToken() {
    const bytes = crypto.getRandomValues(new Uint8Array(16));
    return btoa(String.fromCharCode(...bytes)).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

async function sha256(text) {
    const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
    return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

function bearer(request) {
    const match = /^Bearer (\S+)$/.exec(request.headers.get("Authorization") || "");
    if (match === null || !TOKEN.test(match[1]))
        throw new ApiError(401, "unauthorized");
    return match[1];
}

async function readJson(request) {
    try {
        const body = await request.json();
        if (body === null || typeof body !== "object")
            throw new Error();
        return body;
    } catch (error) {
        throw new ApiError(400, "invalid-body");
    }
}

function checkString(value, maxLength) {
    if (typeof value !== "string" || value.length === 0)
        throw new ApiError(400, "invalid-body");
    if (value.length > maxLength)
        throw new ApiError(413, "too-large");
    return value;
}

async function getPoll(db, pollId) {
    if (!TOKEN.test(pollId))
        throw new ApiError(404, "not-found");
    const poll = await db.prepare("SELECT * FROM polls WHERE id = ?").bind(pollId).first();
    if (poll === null || poll.expires < Date.now())
        throw new ApiError(404, "not-found");
    return poll;
}

async function checkAdmin(request, poll) {
    if (await sha256(bearer(request)) !== poll.admin_hash)
        throw new ApiError(403, "forbidden");
}

async function insertPoll(db, pollId, adminToken, definition, closed) {
    const now = Date.now();
    // The expired polls.
    await db.prepare("DELETE FROM responses WHERE poll_id IN (SELECT id FROM polls WHERE expires < ?)").bind(now).run();
    await db.prepare("DELETE FROM publications WHERE poll_id IN (SELECT id FROM polls WHERE expires < ?)").bind(now).run();
    await db.prepare("DELETE FROM polls WHERE expires < ?").bind(now).run();
    await db.prepare(
        "INSERT INTO polls (id, admin_hash, definition, closed, created, updated, expires) VALUES (?, ?, ?, ?, ?, ?, ?)")
        .bind(pollId, await sha256(adminToken), definition, Number(closed), now, now, now + EXPIRATION)
        .run();
}

async function createPoll(request, db) {
    const body = await readJson(request);
    const adminToken = body.adminToken;
    if (typeof adminToken !== "string" || !TOKEN.test(adminToken))
        throw new ApiError(400, "invalid-body");
    const definition = checkString(body.definition, LIMITS.definitionLength);
    const pollId = randomToken();
    await insertPoll(db, pollId, adminToken, definition, false);
    return json({pollId}, 201);
}

async function readPoll(db, pollId) {
    const poll = await getPoll(db, pollId);
    return json({definition: poll.definition, closed: poll.closed === 1});
}

async function updatePoll(request, db, pollId) {
    let poll;
    try {
        poll = await getPoll(db, pollId);
    } catch (error) {
        if (!(error instanceof ApiError && error.code === "not-found" && TOKEN.test(pollId)))
            throw error;
        poll = null;
    }
    const body = await readJson(request);
    if (body.closed !== undefined && typeof body.closed !== "boolean")
        throw new ApiError(400, "invalid-body");
    if (poll === null) {
        // Creation, with the id generated by the browser.
        const adminToken = bearer(request);
        const definition = checkString(body.definition, LIMITS.definitionLength);
        await insertPoll(db, pollId, adminToken, definition, body.closed === true);
        return json({definition, closed: body.closed === true}, 201);
    }
    await checkAdmin(request, poll);
    const definition = (body.definition === undefined)?
        poll.definition:
        checkString(body.definition, LIMITS.definitionLength);
    const closed = (body.closed === undefined)? poll.closed: Number(body.closed);
    const now = Date.now();
    await db.prepare("UPDATE polls SET definition = ?, closed = ?, updated = ?, expires = ? WHERE id = ?")
        .bind(definition, closed, now, now + EXPIRATION, pollId)
        .run();
    return json({definition, closed: closed === 1});
}

async function deletePoll(request, db, pollId) {
    const poll = await getPoll(db, pollId);
    await checkAdmin(request, poll);
    await db.prepare("DELETE FROM responses WHERE poll_id = ?").bind(pollId).run();
    await db.prepare("DELETE FROM publications WHERE poll_id = ?").bind(pollId).run();
    await db.prepare("DELETE FROM polls WHERE id = ?").bind(pollId).run();
    return new Response(null, {status: 204});
}

// Replace the publications of a poll (atomically).
async function writePublications(request, db, pollId) {
    const poll = await getPoll(db, pollId);
    await checkAdmin(request, poll);
    const {publications} = await readJson(request);
    if (!Array.isArray(publications) || publications.length > 2 * LIMITS.responsesPerPoll)
        throw new ApiError(400, "invalid-body");
    const statements = [db.prepare("DELETE FROM publications WHERE poll_id = ?").bind(pollId)];
    const ids = new Set();
    for (const publication of publications) {
        if (publication === null || typeof publication !== "object" || !TOKEN.test(publication.responseId)
                || ids.has(publication.responseId)
                || (publication.tokenHash !== undefined && !/^[0-9a-f]{64}$/.test(publication.tokenHash)))
            throw new ApiError(400, "invalid-body");
        ids.add(publication.responseId);
        const data = checkString(publication.data, LIMITS.publicationLength);
        statements.push(db.prepare(
            "INSERT INTO publications (poll_id, response_id, token_hash, data) VALUES (?, ?, ?, ?)")
            .bind(pollId, publication.responseId, publication.tokenHash ?? null, data));
    }
    // A modification of the poll.
    const now = Date.now();
    statements.push(db.prepare("UPDATE polls SET updated = ?, expires = ? WHERE id = ?").bind(now, now + EXPIRATION, pollId));
    await db.batch(statements);
    return json({count: publications.length});
}

async function deletePublications(request, db, pollId) {
    const poll = await getPoll(db, pollId);
    await checkAdmin(request, poll);
    await db.prepare("DELETE FROM publications WHERE poll_id = ?").bind(pollId).run();
    return new Response(null, {status: 204});
}

// The publication of a response, for the holder of its token.
async function readPublication(request, db, pollId, responseId) {
    await getPoll(db, pollId);
    if (!TOKEN.test(responseId))
        throw new ApiError(404, "not-found");
    const tokenHash = await sha256(bearer(request));
    const publication = await db.prepare(
        "SELECT data, token_hash FROM publications WHERE poll_id = ? AND response_id = ?")
        .bind(pollId, responseId)
        .first();
    if (publication === null)
        throw new ApiError(404, "not-found");
    const response = await db.prepare("SELECT token_hash FROM responses WHERE poll_id = ? AND id = ?")
        .bind(pollId, responseId)
        .first();
    if (publication.token_hash !== tokenHash && (response === null || response.token_hash !== tokenHash))
        throw new ApiError(403, "forbidden");
    return json({data: publication.data});
}

async function readResponses(request, db, pollId) {
    const poll = await getPoll(db, pollId);
    await checkAdmin(request, poll);
    const {results} = await db.prepare(
        "SELECT id, data, updated FROM responses WHERE poll_id = ? ORDER BY created")
        .bind(pollId)
        .all();
    return json({responses: results.map((r) => ({id: r.id, data: r.data, updated: r.updated}))});
}

// The response of a student, for them to modify it (e.g. on another device).
async function readResponse(request, db, pollId, responseId) {
    await getPoll(db, pollId);
    if (!TOKEN.test(responseId))
        throw new ApiError(404, "not-found");
    const tokenHash = await sha256(bearer(request));
    const response = await db.prepare("SELECT token_hash, data, updated FROM responses WHERE poll_id = ? AND id = ?")
        .bind(pollId, responseId)
        .first();
    if (response === null)
        throw new ApiError(404, "not-found");
    if (response.token_hash !== tokenHash)
        throw new ApiError(403, "forbidden");
    return json({data: response.data, updated: response.updated});
}

async function writeResponse(request, db, pollId, responseId) {
    const poll = await getPoll(db, pollId);
    if (poll.closed === 1)
        throw new ApiError(403, "closed");
    if (!TOKEN.test(responseId))
        throw new ApiError(404, "not-found");
    const tokenHash = await sha256(bearer(request));
    const data = checkString((await readJson(request)).data, LIMITS.responseLength);
    const now = Date.now();
    // A response is a modification of the poll: it doesn't expire.
    await db.prepare("UPDATE polls SET expires = ? WHERE id = ?").bind(now + EXPIRATION, pollId).run();
    const existing = await db.prepare("SELECT token_hash FROM responses WHERE poll_id = ? AND id = ?")
        .bind(pollId, responseId)
        .first();
    if (existing !== null) {
        if (existing.token_hash !== tokenHash)
            throw new ApiError(403, "forbidden");
        await db.prepare("UPDATE responses SET data = ?, updated = ? WHERE poll_id = ? AND id = ?")
            .bind(data, now, pollId, responseId)
            .run();
        return json({updated: now});
    }
    const {count} = await db.prepare("SELECT COUNT(*) AS count FROM responses WHERE poll_id = ?")
        .bind(pollId)
        .first();
    if (count >= LIMITS.responsesPerPoll)
        throw new ApiError(403, "too-many-responses");
    await db.prepare(
        "INSERT INTO responses (poll_id, id, token_hash, data, created, updated) VALUES (?, ?, ?, ?, ?, ?)")
        .bind(pollId, responseId, tokenHash, data, now, now)
        .run();
    return json({updated: now}, 201);
}

async function getProject(request, db, projectId) {
    if (!TOKEN.test(projectId))
        throw new ApiError(404, "not-found");
    const tokenHash = await sha256(bearer(request));
    const project = await db.prepare("SELECT * FROM projects WHERE id = ?").bind(projectId).first();
    if (project === null || project.expires < Date.now())
        return {tokenHash, project: null};
    if (project.token_hash !== tokenHash)
        throw new ApiError(403, "forbidden");
    return {tokenHash, project};
}

async function readProject(request, db, projectId) {
    const {project} = await getProject(request, db, projectId);
    if (project === null)
        throw new ApiError(404, "not-found");
    return json({data: project.data, version: project.version});
}

async function writeProject(request, db, projectId) {
    const {tokenHash, project} = await getProject(request, db, projectId);
    const body = await readJson(request);
    const data = checkString(body.data, LIMITS.projectLength);
    if (!Number.isInteger(body.version) || body.version < 0)
        throw new ApiError(400, "invalid-body");
    const now = Date.now();
    if (project === null) {
        // Created ('version' 0), or deleted (or expired) by another device.
        if (body.version !== 0)
            throw new ApiError(404, "not-found");
        await db.prepare("DELETE FROM projects WHERE expires < ?").bind(now).run();
        await db.prepare(
            "INSERT INTO projects (id, token_hash, data, version, created, updated, expires) VALUES (?, ?, ?, 1, ?, ?, ?)")
            .bind(projectId, tokenHash, data, now, now, now + EXPIRATION)
            .run();
        return json({version: 1}, 201);
    }
    if (body.version !== project.version) {
        return json({error: "conflict", version: project.version, data: project.data}, 409);
    }
    // Only if the version didn't change since it was read (by another
    // request at the same time).
    const {meta} = await db.prepare(
        "UPDATE projects SET data = ?, version = ?, updated = ?, expires = ? WHERE id = ? AND version = ?")
        .bind(data, project.version + 1, now, now + EXPIRATION, projectId, project.version)
        .run();
    if (meta.changes === 0) {
        const current = await db.prepare("SELECT data, version FROM projects WHERE id = ?").bind(projectId).first();
        if (current === null)
            throw new ApiError(404, "not-found");
        return json({error: "conflict", version: current.version, data: current.data}, 409);
    }
    return json({version: project.version + 1});
}

async function deleteProject(request, db, projectId) {
    const {project} = await getProject(request, db, projectId);
    if (project === null)
        throw new ApiError(404, "not-found");
    await db.prepare("DELETE FROM projects WHERE id = ?").bind(projectId).run();
    return new Response(null, {status: 204});
}

function handleProjects(request, db, path) {
    // ['api', 'projects', projectId]
    if (path.length !== 3)
        throw new ApiError(404, "not-found");
    if (request.method === "GET")
        return readProject(request, db, path[2]);
    if (request.method === "PUT")
        return writeProject(request, db, path[2]);
    if (request.method === "DELETE")
        return deleteProject(request, db, path[2]);
    throw new ApiError(405, "method-not-allowed");
}

// Answer a request to '/api/...'.
export async function handleApi(request, env) {
    try {
        if (env.DB === undefined)
            throw new ApiError(503, "no-database");
        const db = env.DB;
        await initialize(db);
        const path = new URL(request.url).pathname.replace(/\/+$/, "").split("/").slice(1);
        const method = request.method;
        if (path[0] === "api" && path[1] === "projects")
            return await handleProjects(request, db, path);
        // ['api', 'polls', pollId?, 'responses'?, responseId?]
        if (path[0] !== "api" || path[1] !== "polls")
            throw new ApiError(404, "not-found");
        if (path.length === 2 && method === "POST")
            return await createPoll(request, db);
        if (path.length === 3) {
            if (method === "GET")
                return await readPoll(db, path[2]);
            if (method === "PUT")
                return await updatePoll(request, db, path[2]);
            if (method === "DELETE")
                return await deletePoll(request, db, path[2]);
        }
        if (path.length === 4 && path[3] === "responses" && method === "GET")
            return await readResponses(request, db, path[2]);
        if (path.length === 4 && path[3] === "publications") {
            if (method === "PUT")
                return await writePublications(request, db, path[2]);
            if (method === "DELETE")
                return await deletePublications(request, db, path[2]);
        }
        if (path.length === 6 && path[3] === "responses" && path[5] === "publication" && method === "GET")
            return await readPublication(request, db, path[2], path[4]);
        if (path.length === 5 && path[3] === "responses") {
            if (method === "GET")
                return await readResponse(request, db, path[2], path[4]);
            if (method === "PUT")
                return await writeResponse(request, db, path[2], path[4]);
        }
        throw new ApiError(path.length <= 6? 405: 404, path.length <= 6? "method-not-allowed": "not-found");
    } catch (error) {
        if (error instanceof ApiError)
            return json({error: error.code}, error.status);
        console.error(error);
        return json({error: "internal"}, 500);
    }
}
